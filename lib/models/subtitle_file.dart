/// A video's subtitles as its source serves them.
class SubtitleFile {
  const SubtitleFile({
    required this.languageCode,
    required this.webVtt,
    this.autoGenerated = false,
  });

  /// The language they are in, such as `en` or `pt-BR`.
  final String languageCode;

  /// The subtitles in WebVTT, the format sources serve on the web.
  final String webVtt;

  /// Whether they were made by speech recognition rather than written.
  final bool autoGenerated;
}
